package com.etendoerp.metadata.builders;

import java.util.List;
import java.util.function.Supplier;

import org.codehaus.jettison.json.JSONException;
import org.codehaus.jettison.json.JSONObject;
import org.openbravo.client.application.window.OBViewTab;
import org.openbravo.data.Sqlc;
import org.openbravo.model.ad.datamodel.Column;
import org.openbravo.model.ad.ui.Process;
import org.openbravo.model.ad.ui.Tab;

/**
 * Resolves the Print / Email toolbar configuration of a tab with the same rules as Etendo
 * Classic ({@code OBViewTab.getIconButtons} and {@code OBViewTab.PrintButton}):
 * <ul>
 * <li>Print is offered when the tab has a print process ({@code AD_Tab.AD_Process_ID}).</li>
 * <li>Email is offered when the print URL belongs to orders, invoices or payments.</li>
 * </ul>
 * The decision depends on the tab configuration only, never on the (translatable) process name.
 */
public final class TabPrintConfig {

  /** Key of the print configuration object in the tab JSON. */
  public static final String PRINT_CONFIG = "printConfig";
  /** Classic print URL of the tab process, as built by {@code OBViewTab.getPrintUrl}. */
  public static final String URL = "url";
  /** Whether the Email button is offered. */
  public static final String HAS_EMAIL = "hasEmail";
  /** Whether printing must be delegated to the Classic {@code PrinterReports} flow. */
  public static final String LEGACY = "legacy";
  /** The process {@code isDirectPrint} flag, sent as Classic {@code inpdirectprint}. */
  public static final String DIRECT_PRINT = "directPrint";
  /** Request parameter name of the tab key column, the Classic {@code inpKeyName}. */
  public static final String KEY_PARAM = "keyParam";

  /** URL fragments Classic checks to offer the Email button ({@code OBViewTab.PrintButton}). */
  private static final List<String> EMAIL_URL_FRAGMENTS = List.of("orders", "invoices", "payments");
  /**
   * Mapping of the PrintController documents (orders, invoices, shipments, payments). Their PDF
   * is generated by the document print service; any other print process is delegated to Classic.
   */
  private static final String PRINT_CONTROLLER_PAGE = "print.html";
  private static final String INPUT_PREFIX = "inp";

  private TabPrintConfig() {
  }

  /**
   * Builds the print configuration of a tab.
   *
   * @param tab       the tab whose print process is resolved
   * @param keyColumn supplies the key column of the tab table ({@code null} when it has none);
   *                  only called when the tab has a print process
   * @return the configuration, or {@code null} when the tab has no print process
   * @throws JSONException if the JSON object cannot be written
   */
  public static JSONObject toJSON(Tab tab, Supplier<Column> keyColumn) throws JSONException {
    Process process = tab.getProcess();
    if (process == null) {
      return null;
    }
    String url = OBViewTab.getPrintUrl(tab);
    JSONObject config = new JSONObject();
    config.put(URL, url);
    config.put(HAS_EMAIL, hasEmail(url));
    config.put(LEGACY, !url.contains(PRINT_CONTROLLER_PAGE));
    config.put(DIRECT_PRINT, Boolean.TRUE.equals(process.isDirectPrint()));
    config.put(KEY_PARAM, getKeyParam(keyColumn.get()));
    return config;
  }

  private static boolean hasEmail(String url) {
    return EMAIL_URL_FRAGMENTS.stream().anyMatch(url::contains);
  }

  private static Object getKeyParam(Column keyColumn) {
    if (keyColumn == null) {
      return JSONObject.NULL;
    }
    return INPUT_PREFIX + Sqlc.TransformaNombreColumna(keyColumn.getDBColumnName());
  }
}
